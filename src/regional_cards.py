"""D3 - Data-backed rationale: one Regional Card per grid region -> docs/regional_cards.md and
outputs/resource_scorecard.csv (0-5 'revealed strength' scores for the radar chart).

Every number comes from NPP (region-wise generation by fuel FY2019-FY2026), the organiser CSV (population, GSDP,
RE-fleet composition) or the pipeline's outputs. No external facts and no assumed values.
Revealed strength = location quotient: the region's share of India's output of a technology divided by its share
of India's total generation (LQ > 1 = the region specialises in it).
"""
import numpy as np
import pandas as pd
from src.config import OUT, DOCS, PROC, REGIONS, REGION_NAME, TECHS, BASE_FY


def lq_table(m):
    return m.div(m.sum(axis=0), axis=1).div(m.sum(axis=1) / m.values.sum(), axis=0)


def build():
    t = pd.read_csv(OUT / "forecast_region_year.csv")
    k = pd.read_csv(OUT / "kpis.csv")
    mp = pd.read_csv(OUT / "mix_pathway.csv")
    npp = pd.read_csv(PROC / "npp_region_fuel_fy.csv")
    sp = pd.read_csv(PROC / "region_panel.csv")
    comp = pd.read_csv(PROC / "csv_re_composition.csv")
    sel = pd.read_csv(OUT / "mix_model_selection.csv")
    val = pd.read_csv(OUT / "mix_validation.csv")
    mb = mp[mp.scenario == "Base"]
    m47 = mb[mb.year == 2047].pivot_table(index="region", columns="tech", values="twh")[TECHS].reindex(REGIONS)
    m0 = mb[mb.year == BASE_FY].pivot_table(index="region", columns="tech", values="twh")[TECHS].reindex(REGIONS)
    lq47, lq0 = lq_table(m47), lq_table(m0)
    score = (5 * lq47.div(lq47.max(axis=0), axis=1)).round(1)          # 5 = the region with the highest LQ for that source
    score.to_csv(OUT / "resource_scorecard.csv")
    out = ["# Regional Cards (D3: data-backed rationale)", "",
           "Generated by `src/regional_cards.py`. Data: National Power Portal region-wise generation by fuel (sub-report 16, "
           "FY2019-FY2026) and the organiser CSV (population, real GSDP, RE-fleet composition). No assumed values. "
           "LQ = location quotient: region's share of India's output of a technology / its share of India's generation "
           "(LQ > 1 = a regional strength). TWh = energy generated.", ""]
    nat_fuel = npp[npp.region.isin(REGIONS)].groupby("FY")[["Coal", "Gas", "Hydro", "Nuclear"]].sum()
    for r in REGIONS:
        g = t[(t.region == r) & (t.scenario == "Base")].set_index("year")
        n = npp[npp.region == r].set_index("FY")
        s = sp[sp.region == r].set_index("FY")
        kk = k[(k.scenario == "Base") & (k.region == r)].set_index("year")
        tot47, tot0 = m47.loc[r].sum(), m0.loc[r].sum()
        conv = n[["Coal", "Gas", "Hydro", "Nuclear"]].sum(axis=1)
        pg = 100 * ((s.loc[2025, "pop"] / s.loc[2016, "pop"]) ** (1 / 9) - 1)
        yg = 100 * ((s.loc[2025, "gsdp_pc"] / s.loc[2016, "gsdp_pc"]) ** (1 / 9) - 1)
        pc_rank = sp[sp.FY == BASE_FY].set_index("region").gsdp_pc.rank(ascending=False).astype(int)[r]
        strengths = lq47.loc[r][lq47.loc[r] > 1].sort_values(ascending=False)
        rs = comp[(comp.kind == "region_share_of_tech") & (comp.region == r) & (comp.FY == BASE_FY)].set_index("tech").share
        bullets = []
        for f in ("Coal", "Gas", "Hydro", "Nuclear"):
            if n[f].max() <= 0:
                bullets.append(f"*{f}*: NPP shows no {f.lower()} generation in this region FY2019-FY2026 → 0 in the forecast")
                continue
            sh = 100 * n[f] / nat_fuel[f]
            bullets.append(f"*{f}*: NPP {n.loc[2019, f]:,.1f} → {n.loc[2026, f]:,.1f} TWh FY2019-FY2026; share of India's {f.lower()} "
                           f"{sh.loc[2019]:.0f}% → {sh.loc[2026]:.0f}% | 2047: {m47.loc[r, f]:,.0f} TWh (LQ {lq47.loc[r, f]:.2f})")
        for tk in ("Solar", "Wind", "Other RE"):
            bullets.append(f"*{tk}*: region holds {100*rs.get(tk, 0):.0f}% of the CSV national {tk} fleet (FY{BASE_FY}) → "
                           f"{m0.loc[r, tk]:,.1f} TWh of NPP RES in FY{BASE_FY} | 2047: {m47.loc[r, tk]:,.0f} TWh (LQ {lq47.loc[r, tk]:.2f})")
        vr = val[(val.region == r)]
        verr = vr.groupby("FY").apply(lambda x: 100 * (x.forecast.sum() / x.actual.sum() - 1), include_groups=False)
        out += [f"## {REGION_NAME[r]} region [{r}]", "",
                f"**Demand drivers (CSV).** Population {g.loc[BASE_FY,'pop_m']:.0f} M → {g.loc[2047,'pop_m']:.0f} M "
                f"(CSV FY2016-25 growth {pg:.2f}%/yr); real GSDP per person rank {pc_rank} of 5, growing {yg:.1f}%/yr FY2016-25; "
                f"regional real GSDP ×{g.loc[2047,'gsdp_index']:.1f} by 2047.",
                f"**NPP history.** Conventional generation (coal + gas + hydro + nuclear) {conv.loc[2019]:,.0f} → {conv.loc[2026]:,.0f} TWh "
                f"FY2019-FY2026 ({100*((conv.loc[2026]/conv.loc[2019])**(1/7)-1):+.1f}%/yr).", "",
                f"**2047 requirement:** {g.loc[2047,'p50']:,.0f} TWh (P10 {g.loc[2047,'p10']:,.0f} – P90 {g.loc[2047,'p90']:,.0f}); "
                f"FY{BASE_FY} {g.loc[BASE_FY,'p50']:,.0f} TWh.", "",
                "**Revealed strengths 2047 (LQ > 1):** " + (", ".join(f"{tk} {v:.2f}" for tk, v in strengths.items()) or "none") +
                f". FY{BASE_FY}: " + ", ".join(f"{tk} {v:.2f}" for tk, v in lq0.loc[r][lq0.loc[r] > 1].sort_values(ascending=False).items()) + ".", "",
                "**2047 generation located here:** " + ", ".join(f"{tk} {m47.loc[r, tk]:,.0f} TWh ({100*m47.loc[r, tk]/tot47:.0f}%)"
                                                               for tk in TECHS if m47.loc[r, tk] > 0.5) +
                f". Total {tot47:,.0f} TWh (FY{BASE_FY} {tot0:,.0f}); non-fossil {100*kk.loc[2047,'nonfossil_share']:.0f}% "
                f"(FY{BASE_FY} {100*kk.loc[BASE_FY,'nonfossil_share']:.0f}%); implied net "
                f"{'export' if kk.loc[2047,'net_export_twh'] >= 0 else 'import'} {abs(kk.loc[2047,'net_export_twh']):,.0f} TWh "
                "(generation located here − requirement).", "",
                "**Why this mix – the data behind each source:**", ""]
        out += [f"- {b}" for b in bullets]
        out += ["", f"**Out-of-sample check.** Regional conventional generation forecast vs NPP actual: "
                + ", ".join(f"FY{int(y)} {v:+.1f}%" for y, v in verr.items()) + ".", ""]
    out += ["## How the shares are forecast", "",
            "Each share is projected by the model family that predicted best on a hold-out (constant share, multinomial-logit "
            "trend, or recent-increments), blended with inverse-error weights:", "",
            sel[sel.weight > 0][["panel", "family", "param", "MAE_pp", "weight"]].round(3).to_markdown(index=False), ""]
    (DOCS / "regional_cards.md").write_text("\n".join(out))
    print("[cards] docs/regional_cards.md written")


if __name__ == "__main__":
    build()
